/** "2026-11-04" → "Nov 4, 2026" (parsed as a local date, never shifted by timezone). */
export function formatPlayDate(iso: string): string {
  const [y, m, d] = iso.split("-").map(Number);
  if (!y || !m || !d) return iso;
  return new Date(y, m - 1, d).toLocaleDateString("en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
  });
}
