/**
 * Generates src/data/setsByCardName.ts from @flesh-and-blood/cards (Release strings).
 * Run: node scripts/build-sets-by-name.mjs
 */
import { writeFileSync } from "fs";
import { fileURLToPath } from "url";
import { dirname, join } from "path";
import { cards, releases } from "@flesh-and-blood/cards";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");

// Skip products that aren't out yet (see generate-cards.mjs for the same rule).
const CUTOFF = process.env.FAB_RELEASED_BEFORE
  ? Date.parse(process.env.FAB_RELEASED_BEFORE + "T23:59:59Z")
  : Date.now();
const releaseDate = new Map(releases.map((r) => [String(r.release), r.releaseDate]));
function isOut(name) {
  const d = releaseDate.get(name);
  return !d || Date.parse(d.replace(" ", "T") + "Z") <= CUTOFF;
}

const nameToSets = new Map();

for (const card of cards) {
  const names = new Set();
  for (const s of card.sets ?? []) names.add(String(s));
  for (const p of card.printings ?? []) {
    if (p.set != null) names.add(String(p.set));
  }
  for (const n of names) if (!isOut(n)) names.delete(n);
  if (names.size === 0) continue;
  const key = card.name;
  if (!nameToSets.has(key)) nameToSets.set(key, new Set());
  for (const n of names) nameToSets.get(key).add(n);
}

const entries = [...nameToSets.entries()]
  .map(([name, set]) => [name, [...set].sort((a, b) => a.localeCompare(b))])
  .sort((a, b) => a[0].localeCompare(b[0]));

const lines = entries.map(([name, sets]) => {
  const key = JSON.stringify(name);
  const val = JSON.stringify(sets);
  return `  ${key}: ${val},`;
});

const out = `/* Auto-generated by scripts/build-sets-by-name.mjs — do not edit by hand */
export const SETS_BY_CARD_NAME: Record<string, readonly string[]> = {
${lines.join("\n")}
};
`;

writeFileSync(join(root, "src", "data", "setsByCardName.ts"), out, "utf8");
console.log("Wrote src/data/setsByCardName.ts", entries.length, "cards");
