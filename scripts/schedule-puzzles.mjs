/**
 * (Re)generates the daily puzzle schedule in Supabase `daily_puzzles` from the
 * current src/data/cards.ts.
 *
 * - Only dates from --from onward are touched, so past and today's puzzles stay.
 * - Cards that were already an answer before --from are skipped, and no card is
 *   used twice in the new schedule (until the pool runs out).
 * - Picks are a seeded shuffle, so the same inputs give the same schedule.
 *
 * Usage:
 *   node scripts/schedule-puzzles.mjs [--from YYYY-MM-DD] [--to YYYY-MM-DD]
 *        [--seed text] [--used ids.json] [--sql out.sql] [--apply]
 *
 *   --from   first date to (re)schedule. Default: tomorrow (UTC).
 *   --to     last date. Default: one year after --from.
 *   --used   JSON array of card ids already used as answers. If omitted and
 *            SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY are set, they're read
 *            from daily_puzzles (play_date < --from).
 *   --sql    write an upsert SQL file you can paste into the SQL editor.
 *   --apply  upsert directly (needs SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY).
 *
 * Deploy the matching cards.ts first: the live site rejects card ids it
 * doesn't know about.
 */

import { readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";
import { createClient } from "@supabase/supabase-js";

const __dirname = dirname(fileURLToPath(import.meta.url));

const args = process.argv.slice(2);
const opt = (name) => {
  const i = args.indexOf(`--${name}`);
  return i === -1 ? undefined : args[i + 1];
};
const flag = (name) => args.includes(`--${name}`);

const DAY = 86_400_000;
const toDate = (ms) => new Date(ms).toISOString().slice(0, 10);
const parse = (s) => {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(s)) throw new Error(`Bad date: ${s}`);
  return Date.parse(`${s}T00:00:00Z`);
};

const todayUtc = parse(new Date().toISOString().slice(0, 10));
const from = opt("from") ? parse(opt("from")) : todayUtc + DAY;
const to = opt("to") ? parse(opt("to")) : parse(`${Number(toDate(from).slice(0, 4)) + 1}${toDate(from).slice(4)}`) - DAY;
if (to < from) throw new Error("--to is before --from");
if (from <= todayUtc && !flag("allow-today")) {
  throw new Error("Refusing to change today's or past puzzles (pass --allow-today to override).");
}
const seed = opt("seed") ?? toDate(from);

// ── Cards ───────────────────────────────────────────────────────────────────
const cardsTs = readFileSync(join(__dirname, "..", "src", "data", "cards.ts"), "utf8");
const allIds = [...cardsTs.matchAll(/^\s*\{id:"([^"]+)"/gm)].map((m) => m[1]);

// ── Used answers ────────────────────────────────────────────────────────────
const url = process.env.SUPABASE_URL;
const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
const supabase = url && key ? createClient(url, key) : null;

let used = [];
if (opt("used")) {
  used = JSON.parse(readFileSync(opt("used"), "utf8"));
} else if (supabase) {
  const { data, error } = await supabase
    .from("daily_puzzles")
    .select("card_id")
    .lt("play_date", toDate(from));
  if (error) throw error;
  used = data.map((r) => r.card_id);
} else {
  console.warn("No --used file or Supabase credentials: past answers won't be excluded.");
}
const usedSet = new Set(used);

// ── Seeded shuffle (mulberry32 over an FNV-1a hash of the seed) ─────────────
let h = 0x811c9dc5;
for (const ch of seed) h = Math.imul(h ^ ch.charCodeAt(0), 0x01000193) >>> 0;
const rand = () => {
  h = (h + 0x6d2b79f5) >>> 0;
  let t = h;
  t = Math.imul(t ^ (t >>> 15), t | 1);
  t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};
const shuffle = (arr) => {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
};

const fresh = shuffle(allIds.filter((id) => !usedSet.has(id)));
const reuse = shuffle(allIds.filter((id) => usedSet.has(id)));
const pool = [...fresh, ...reuse];

const rows = [];
for (let t = from, i = 0; t <= to; t += DAY, i++) {
  rows.push({ play_date: toDate(t), card_id: pool[i % pool.length] });
}

console.log(`Cards: ${allIds.length}, already used: ${usedSet.size}, fresh: ${fresh.length}`);
console.log(`Scheduling ${rows.length} days: ${rows[0].play_date} → ${rows.at(-1).play_date} (seed "${seed}")`);
if (rows.length > fresh.length) console.warn(`Only ${fresh.length} fresh cards, so some answers repeat.`);

// ── Output ──────────────────────────────────────────────────────────────────
if (opt("sql")) {
  const values = rows.map((r) => `  ('${r.play_date}', '${r.card_id.replace(/'/g, "''")}')`).join(",\n");
  const sql =
    `-- Generated by scripts/schedule-puzzles.mjs (seed "${seed}")\n` +
    `insert into public.daily_puzzles (play_date, card_id) values\n${values}\n` +
    `on conflict (play_date) do update set card_id = excluded.card_id;\n`;
  writeFileSync(opt("sql"), sql, "utf8");
  console.log(`Wrote ${opt("sql")}`);
}

if (flag("apply")) {
  if (!supabase) throw new Error("--apply needs SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY");
  const { error } = await supabase.from("daily_puzzles").upsert(rows, { onConflict: "play_date" });
  if (error) throw error;
  console.log(`Upserted ${rows.length} rows.`);
}

if (!opt("sql") && !flag("apply")) {
  rows.slice(0, 7).forEach((r) => console.log(`  ${r.play_date}  ${r.card_id}`));
  console.log("Dry run. Pass --sql <file> or --apply to write the schedule.");
}
